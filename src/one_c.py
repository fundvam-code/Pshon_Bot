"""Работа с базой 1С:Альфа авто 5 (платформа 8.3) через COM-коннектор V83.COMConnector.

Бот ничего не хранит у себя: все поиски и записи выполняются прямо в информационной базе.
Модуль содержит один класс OneC и исключение OneCError.

Важные особенности:
- COM-коннектор платформы 32-битный, поэтому и Python должен быть 32-битным (см. run_bot.py).
- Идентификаторы объектов наружу отдаются строкой (GUID, через XMLString), а обратно
  превращаются в ссылку методами _ref / _order_ref.
- Все записи, затрагивающие несколько объектов, выполняются в транзакции 1С и при любой
  ошибке откатываются целиком.
- Ошибки, которые можно показать пользователю бота, поднимаются как OneCError.
- Структура данных базы (справочники, регистры, обязательные поля) описана в STRUCTURE.md.
"""
import datetime
import logging
import re
import uuid
from typing import Dict, List, Optional

import pywintypes
import win32com.client

from config import quote_1c

logger = logging.getLogger(__name__)

SEARCH_LIMIT = 10


class OneCError(Exception):
    """Ошибка работы с 1С.

    Текст исключения написан для пользователя бота и показывается в чате как есть
    (например, «Нет связи с 1С», «Эта работа уже есть в заказ-наряде»).
    """


class OneC:
    """Клиент базы 1С:Альфа авто: подключение, поиск и запись клиентов, машин, заказ-нарядов.

    Один экземпляр держит одно COM-соединение (атрибут c) и используется из одного потока,
    в котором оно создано (бот работает в одном потоке asyncio, поэтому это соблюдается).
    При потере связи соединение сбрасывается (c = None) и переустанавливается при следующем вызове.
    """
    def __init__(self, connection: str, user: str = "", password: str = "",
                 progid: str = "V83.COMConnector", description: str = "", currency: str = "",
                 default_executor: str = ""):
        """Запоминает параметры подключения; само подключение не выполняется (см. connect).

        Параметры:
            connection: часть строки соединения 1С без логина и пароля: File='<каталог базы>' для
                файловой базы или Srvr='<сервер>';Ref='<база>' для серверной (собирается в
                config.load_settings из настроек .env).
            user: имя пользователя 1С. Ему нужно право «Внешнее соединение».
            password: пароль пользователя 1С (может быть пустым).
            progid: имя COM-коннектора (V83.COMConnector для платформы 8.3).
            description: читаемое описание базы для логов.
            currency: наименование валюты учёта для новых записей (пусто — определить автоматически).
            default_executor: ФИО исполнителя по умолчанию (сотрудник с признаком «Исполнитель»), которого
                бот ставит на работы в заказ-нарядах, созданных через бота.
        """
        self.default_executor = default_executor
        self.connection = connection
        self.user = user
        self.password = password
        self.progid = progid
        self.description = description or connection
        self.currency_name = currency
        self.c = None
        self._currency = None

    # ---------- подключение ----------

    def connect(self) -> bool:
        """Подключается к базе 1С через COM-коннектор (по умолчанию V83.COMConnector).

        Строка соединения: <File=… или Srvr=…;Ref=…>;Usr='<пользователь>';Pwd='<пароль>';
        (именно Usr/Pwd, а не User/Password). Первое подключение может занимать около 30 секунд.

        Возвращает True при успехе. При ошибке пишет её в лог, сбрасывает соединение и возвращает False
        (исключение не поднимается). Типичные причины: «Класс не зарегистрирован» (64-битный Python
        или не зарегистрирован comcntr.dll), «Неверно указан пользователь или пароль»,
        «Внешнее соединение не разрешено для указанного пользователя».
        """
        try:
            connector = win32com.client.Dispatch(self.progid)
            self.c = connector.Connect(
                f"{self.connection};Usr={quote_1c(self.user)};Pwd={quote_1c(self.password)};"
            )
            self._currency = None
            logger.info("Подключено к 1С: %s", self.description)
            return True
        except Exception as e:
            self.c = None
            logger.error("Ошибка подключения к 1С: %s: %s", type(e).__name__, e)
            if isinstance(e, AttributeError) and "Connect" in str(e):
                logger.error(
                    "COM-коннектор 1С создан, но метод Connect недоступен. Обычно это битая регистрация "
                    "comcntr.dll: в терминале ОТ АДМИНИСТРАТОРА выполните regsvr32 \"<каталог 1С>\\bin\\comcntr.dll\" "
                    "для установленной версии платформы (32-битной) и удалите папку %TEMP%\\gen_py. "
                    "Подробности в README (раздел «Типовые ошибки»).")
            return False

    def _ensure(self):
        """Гарантирует наличие соединения: при необходимости пытается подключиться заново.

        Вызывается в начале каждой публичной операции.
        Исключение: OneCError, если подключиться не удалось.
        """
        if self.c is None and not self.connect():
            raise OneCError("Нет связи с 1С. Попробуйте позже.")

    # ---------- вспомогательное ----------

    def _messages(self) -> str:
        """Возвращает сообщения пользователю, накопленные 1С при последней операции.

        Нужен, чтобы получить настоящую причину отказа записи (например, «Реквизит "Валюта учета"
        не заполнен!»): само исключение COM содержит только общую фразу «Не удалось записать».
        Сообщения при этом считываются и очищаются. Пустая строка, если сообщений нет.
        """
        try:
            return "\n".join(m.Текст for m in self.c.ПолучитьСообщенияПользователю(False))
        except Exception:
            return ""

    def _write(self, obj, what: str):
        """Записывает объект (элемент справочника, группу, запись регистра) методом Записать().

        Параметры:
            obj: COM-объект 1С, готовый к записи.
            what: название объекта для сообщения об ошибке («клиент», «автомобиль»…).

        Исключение: OneCError с причиной от 1С (обязательные поля, обработчики «ПередЗаписью» и т.п.).
        Транзакцию метод не открывает и не откатывает: это делает вызывающий код.
        """
        try:
            obj.Записать()
        except pywintypes.com_error as e:
            detail = self._messages()
            logger.error("Не удалось записать %s: %s | %s", what, e, detail)
            raise OneCError(f"1С не приняла запись ({what}): {detail or 'ошибка записи'}")

    def _query(self, text: str, params: Optional[Dict] = None):
        """Выполняет запрос на встроенном языке 1С и возвращает выборку.

        Параметры:
            text: текст запроса на языке запросов 1С (русские ключевые слова).
            params: словарь параметров {имя: значение} для &Имя в запросе.

        Возвращает выборку; обход: while sel.Следующий(): ... sel.ИмяКолонки.
        Внимание: некоторые слова зарезервированы языком запросов и недопустимы как псевдонимы
        колонок (В, И и т.п.).
        """
        q = self.c.NewObject("Запрос")
        q.Текст = text
        for k, v in (params or {}).items():
            q.УстановитьПараметр(k, v)
        return q.Выполнить().Выбрать()

    def _trim(self, catalog_name: str, text: str) -> str:
        """Обрезает наименование до допустимой длины справочника.

        Параметры:
            catalog_name: имя справочника («Контрагенты», «Автомобили», «Автоработы»…).
            text: исходный текст.

        Длина берётся из метаданных 1С (ДлинаНаименования); 0 означает «без ограничения».
        """
        length = getattr(self.c.Метаданные.Справочники, catalog_name).ДлинаНаименования
        return text[:length] if length else text

    def _ref_id(self, ref) -> str:
        """Превращает ссылку 1С в строку-GUID, которую можно хранить и передавать в боте."""
        return self.c.XMLString(ref)

    def _ref(self, catalog_name: str, ref_id: str):
        """Строит ссылку на элемент справочника по строке-GUID.

        Параметры:
            catalog_name: имя справочника («Контрагенты»).
            ref_id: идентификатор, полученный ранее из _ref_id.
        """
        guid = self.c.NewObject("УникальныйИдентификатор", ref_id)
        return getattr(self.c.Справочники, catalog_name).ПолучитьСсылку(guid)

    def _info_kind(self, name: str):
        """Возвращает значение перечисления «Дополнительная информация автомобилей».

        Допустимые имена: Хозяин, ГосНомер, Пробег, ТехПаспорт, ВидАвтомобиля. Именно по ним
        в регистре сведений «Автомобили» различаются данные машины.
        """
        return getattr(self.c.Перечисления.ДополнительнаяИнформацияАвтомобилей, name)

    def _accounting_currency(self):
        """Определяет валюту учёта для новых моделей и автомобилей (обязательное поле 1С).

        Порядок выбора: 1) валюта из переменной окружения ONE_C_CURRENCY (по наименованию);
        2) валюта уже существующих моделей автомобилей; 3) первая валюта справочника без пометки
        удаления. Результат кэшируется до переподключения.
        Исключение: OneCError, если в базе нет ни одной подходящей валюты.
        """
        if self._currency is None:
            cur = self.currency_name
            if cur:
                sel = self._query(
                    "ВЫБРАТЬ ПЕРВЫЕ 1 Вл.Ссылка КАК Ссылка ИЗ Справочник.Валюты КАК Вл "
                    "ГДЕ Вл.Наименование = &Н", {"Н": cur})
            else:
                sel = self._query(
                    "ВЫБРАТЬ ПЕРВЫЕ 1 М.ВалютаУчета КАК Ссылка ИЗ Справочник.Модели КАК М "
                    "ГДЕ НЕ М.ВалютаУчета = ЗНАЧЕНИЕ(Справочник.Валюты.ПустаяСсылка) "
                    "И НЕ М.ВалютаУчета.ПометкаУдаления")
            if not sel.Следующий():
                sel = self._query(
                    "ВЫБРАТЬ ПЕРВЫЕ 1 Вл.Ссылка КАК Ссылка ИЗ Справочник.Валюты КАК Вл "
                    "ГДЕ НЕ Вл.ПометкаУдаления")
                if not sel.Следующий():
                    raise OneCError("В 1С не найдена валюта учёта.")
            self._currency = sel.Ссылка
        return self._currency

    # ---------- поиск ----------

    def find_clients(self, text: str) -> List[Dict]:
        """Ищет клиентов (справочник «Контрагенты») по части ФИО или телефона.

        Параметры:
            text: строка поиска; регистр не важен, спецсимволы (% _ [ \\) экранируются.

        Возвращает до SEARCH_LIMIT (10) записей вида {"id", "name", "phone"}, отсортированных по имени.
        Группы и помеченные на удаление контрагенты пропускаются. Пустой список, если ничего не найдено.
        Исключение: OneCError при ошибке связи с 1С.
        """
        self._ensure()
        escaped = text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_").replace("[", "\\[")
        pattern = f"%{escaped}%"
        digits = re.sub(r"\D", "", text)
        phone_pattern = f"%{digits}%" if digits and re.fullmatch(r"[\d\s+()\-]+", text.strip()) else pattern
        try:
            sel = self._query(
                "ВЫБРАТЬ ПЕРВЫЕ " + str(SEARCH_LIMIT) + " К.Ссылка КАК Ссылка, К.Наименование КАК Имя, "
                "К.ОсновнойТелефон КАК Телефон ИЗ Справочник.Контрагенты КАК К "
                "ГДЕ НЕ К.ЭтоГруппа И НЕ К.ПометкаУдаления "
                "И (К.Наименование ПОДОБНО &Т СПЕЦСИМВОЛ \"\\\" ИЛИ К.ОсновнойТелефон ПОДОБНО &Ф СПЕЦСИМВОЛ \"\\\") "
                "УПОРЯДОЧИТЬ ПО К.Наименование",
                {"Т": pattern, "Ф": phone_pattern})
            result = []
            while sel.Следующий():
                result.append({"id": self._ref_id(sel.Ссылка), "name": sel.Имя, "phone": sel.Телефон or ""})
            return result
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка поиска клиентов: %s", e)
            raise OneCError("Ошибка поиска в 1С.")

    def get_client_cars(self, client_id: str) -> List[Dict]:
        """Возвращает автомобили клиента.

        Параметры:
            client_id: идентификатор клиента (поле "id" из find_clients).

        Владелец определяется по регистру сведений «Автомобили» (вид значения «Хозяин»), читается срез
        последних, поэтому при смене владельца в 1С показывается актуальный. Возвращает список
        {"name", "vin", "year", "gos_number"}; год пуст, если не заполнен.
        Исключение: OneCError при ошибке чтения.
        """
        self._ensure()
        try:
            client = self._ref("Контрагенты", client_id)
            sel = self._query(
                "ВЫБРАТЬ Р.Автомобиль КАК Авто, Р.Автомобиль.Наименование КАК Название, "
                "Р.Автомобиль.VIN КАК Вин, Р.Автомобиль.ГодВыпуска КАК Выпуск "
                "ИЗ РегистрСведений.Автомобили.СрезПоследних КАК Р "
                "ГДЕ Р.ВидЗначения = ЗНАЧЕНИЕ(Перечисление.ДополнительнаяИнформацияАвтомобилей.Хозяин) "
                "И Р.Значение = &Клиент И НЕ Р.Автомобиль.ПометкаУдаления",
                {"Клиент": client})
            cars = []
            while sel.Следующий():
                year = ""
                try:
                    if sel.Выпуск.year > 1900:
                        year = str(sel.Выпуск.year)
                except Exception:
                    pass
                cars.append({"ref": sel.Авто, "name": sel.Название, "vin": sel.Вин or "", "year": year})
            for car in cars:
                ref = car.pop("ref")
                car["id"] = self._ref_id(ref)
                car["gos_number"] = self._car_gos_number(ref)
            return cars
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка получения автомобилей: %s", e)
            raise OneCError("Ошибка чтения автомобилей из 1С.")

    def _car_gos_number(self, car_ref) -> str:
        """Возвращает госномер автомобиля из регистра сведений (вид «ГосНомер») или пустую строку."""
        sel = self._query(
            "ВЫБРАТЬ ПЕРВЫЕ 1 Р.Значение КАК Знач ИЗ РегистрСведений.Автомобили.СрезПоследних КАК Р "
            "ГДЕ Р.Автомобиль = &А И Р.ВидЗначения = "
            "ЗНАЧЕНИЕ(Перечисление.ДополнительнаяИнформацияАвтомобилей.ГосНомер)",
            {"А": car_ref})
        return self.c.String(sel.Знач) if sel.Следующий() and sel.Знач else ""

    def find_car_by_gos_number(self, gos_number: str) -> Optional[Dict]:
        """Ищет автомобиль по госномеру (для защиты от дублей).

        Параметры:
            gos_number: госномер в том виде, в каком он записан в 1С (бот приводит его к верхнему
                регистру и убирает пробелы).

        Возвращает {"name": название авто, "owner": наименование владельца} или None, если такого номера нет.
        """
        self._ensure()
        sel = self._query(
            "ВЫБРАТЬ ПЕРВЫЕ 1 Р.Автомобиль КАК Авто, Р.Автомобиль.Наименование КАК Название "
            "ИЗ РегистрСведений.Автомобили.СрезПоследних КАК Р "
            "ГДЕ Р.ВидЗначения = ЗНАЧЕНИЕ(Перечисление.ДополнительнаяИнформацияАвтомобилей.ГосНомер) "
            "И Р.Значение = &Н И НЕ Р.Автомобиль.ПометкаУдаления",
            {"Н": gos_number})
        if not sel.Следующий():
            return None
        owner = self._query(
            "ВЫБРАТЬ ПЕРВЫЕ 1 Р.Значение КАК Знач ИЗ РегистрСведений.Автомобили.СрезПоследних КАК Р "
            "ГДЕ Р.Автомобиль = &А И Р.ВидЗначения = "
            "ЗНАЧЕНИЕ(Перечисление.ДополнительнаяИнформацияАвтомобилей.Хозяин)",
            {"А": sel.Авто})
        return {"name": sel.Название, "owner": self.c.String(owner.Знач) if owner.Следующий() and owner.Знач else ""}

    def count_open_work_orders(self) -> Dict:
        """Считает и перечисляет незакрытые заказ-наряды (кнопка «Сколько в работе ЗН»).

        Незакрытым считается любой ЗН без пометки удаления, состояние которого не «Закрыт»
        (в том числе «Заявка», «Начать работу», «В работе», «Выполнен»). Счёт ведётся по журналу
        документов «ЗаказНаряд», список — по документам.

        Возвращает {"total": число, "by_state": [(состояние, число)…],
        "orders": [до 40 последних ЗН: number, customer, car, total, currency, state]}.
        Исключение: OneCError при ошибке чтения.
        """
        self._ensure()
        try:
            closed = self._query(
                "ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.ВидыСостоянийЗаказНарядов КАК С "
                "ГДЕ С.Наименование = &Н", {"Н": "Закрыт"})
            closed_ref = closed.Ссылка if closed.Следующий() else self.c.Справочники.ВидыСостоянийЗаказНарядов.ПустаяСсылка()
            sel = self._query(
                "ВЫБРАТЬ Ж.Состояние КАК Сост, КОЛИЧЕСТВО(*) КАК Кол "
                "ИЗ ЖурналДокументов.ЗаказНаряд КАК Ж "
                "ГДЕ Ж.Ссылка ССЫЛКА Документ.ЗаказНаряд И НЕ Ж.ПометкаУдаления И Ж.Состояние <> &Закрыт "
                "СГРУППИРОВАТЬ ПО Ж.Состояние УПОРЯДОЧИТЬ ПО Ж.Состояние.Порядок",
                {"Закрыт": closed_ref})
            by_state = []
            while sel.Следующий():
                by_state.append((self.c.String(sel.Сост) or "Без состояния", int(sel.Кол)))
            rows = self._query(
                "ВЫБРАТЬ ПЕРВЫЕ 40 Д.Номер КАК Номер, Д.Заказчик.Наименование КАК Заказчик, "
                "Д.Автомобиль.Наименование КАК Авто, Д.СуммаРаботДокумента КАК Итого, "
                "Д.ВалютаДокумента.Наименование КАК Валюта, Д.Состояние.Наименование КАК Сост "
                "ИЗ Документ.ЗаказНаряд КАК Д "
                "ГДЕ НЕ Д.ПометкаУдаления И Д.Состояние <> &Закрыт УПОРЯДОЧИТЬ ПО Д.Дата УБЫВ",
                {"Закрыт": closed_ref})
            orders = []
            while rows.Следующий():
                orders.append({"number": str(rows.Номер).lstrip("0") or "0", "customer": rows.Заказчик or "—",
                               "car": rows.Авто or "—", "total": float(rows.Итого),
                               "currency": rows.Валюта or "", "state": rows.Сост or "Без состояния"})
            return {"total": sum(n for _, n in by_state), "by_state": by_state, "orders": orders}
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка подсчёта заказ-нарядов: %s", e)
            raise OneCError("Ошибка чтения журнала заказ-нарядов из 1С.")

    # ---------- заказ-наряды: просмотр ----------

    WORK_GROUP = "Работы для разнесения"

    def _order_ref(self, order_id: str):
        """Строит ссылку на документ «ЗаказНаряд» по строке-GUID."""
