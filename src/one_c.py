    @staticmethod
    def normalize_article(article: str) -> str:
        """Артикул для сравнения: без пробелов и в верхнем регистре (так 1С хранит «Артикул для поиска»)."""
        return "".join(article.split()).upper()

    def find_parts_by_article(self, article: str) -> List[Dict]:
        """Ищет запчасти (товары) в справочнике «Номенклатура» по артикулу, а не по названию.

        Артикул сравнивается точно, без учёта регистра и пробелов, и с полем «Артикул», и с «Артикулом для
        поиска». Группы и помеченные на удаление не берутся. Возвращает до 8 записей
        [{"id", "name", "article"}], пустой список, если артикула нет или он не задан.
        Исключение: OneCError при ошибке поиска.
        """
        key = self.normalize_article(article)
        if not key:
            return []
        self._ensure()
        # 1С при записи сама пересчитывает «Артикул для поиска» (верхний регистр, пробелы остаются), поэтому
        # кандидатов отбираем шаблоном «%А%Р%Т%…%» (символы артикула по порядку), а точное сравнение без
        # пробелов и регистра делаем здесь.
        pattern = "%" + "%".join(("\\" + ch) if ch in "\\%_[" else ch for ch in key) + "%"
        try:
            sel = self._query(
                "ВЫБРАТЬ ПЕРВЫЕ 300 Н.Ссылка КАК Ссылка, Н.Наименование КАК Имя, Н.Артикул КАК Арт, "
                "Н.АртикулДляПоиска КАК АртПоиск ИЗ Справочник.Номенклатура КАК Н "
                "ГДЕ НЕ Н.ЭтоГруппа И НЕ Н.ПометкаУдаления "
                "И Н.ВидНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ВидыНоменклатуры.Товар) "
                "И (Н.АртикулДляПоиска ПОДОБНО &П СПЕЦСИМВОЛ \"\\\" ИЛИ Н.Артикул ПОДОБНО &П СПЕЦСИМВОЛ \"\\\") "
                "УПОРЯДОЧИТЬ ПО Н.Наименование", {"П": pattern})
            result = []
            while sel.Следующий():
                if key in (self.normalize_article(sel.Арт or ""), self.normalize_article(sel.АртПоиск or "")):
                    result.append({"id": self._ref_id(sel.Ссылка), "name": sel.Имя, "article": sel.Арт or ""})
                    if len(result) == 8:
                        break
            return result
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка поиска запчасти по артикулу: %s", e)
            raise OneCError("Ошибка поиска запчасти по артикулу в 1С.")

    def _create_part(self, name: str, article: str = ""):
        """Создаёт запчасть в справочнике «Номенклатура» в группе «Запчасти для разнесения».

        Заполняется то, что требует 1С: тип «Штучный», вид «Товар», единица «шт», ставка НДС «Без НДС»,
        валюта учёта, артикул и артикул для поиска. Артикул — заданный пользователем (article); если он
        пуст, создаётся автоматически из названия (название без пробелов, как у существующих позиций).
        Вызывается внутри транзакции add_part и add_customer_part_to_order.
        """
        item = self.c.Справочники.Номенклатура.СоздатьЭлемент()
        item.Родитель = self._parts_group()
        item.Наименование = self._trim("Номенклатура", name)
        item.НаименованиеПолное = name
        part_type = self._first(
            "ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК Ссылка ИЗ Справочник.ТипыНоменклатуры КАК Т ГДЕ Т.Наименование = &Н",
            {"Н": "Штучный"})
        if part_type is None:
            raise OneCError("В 1С не найден тип номенклатуры «Штучный».")
        item.ТипНоменклатуры = part_type
        item.ВидНоменклатуры = self.c.Перечисления.ВидыНоменклатуры.Товар
        base_unit = self._first(
            "ВЫБРАТЬ ПЕРВЫЕ 1 Е.Ссылка КАК Ссылка ИЗ Справочник.КлассификаторЕдиницИзмерения КАК Е "
            "ГДЕ Е.Наименование = &Н", {"Н": "шт"})
        if base_unit is not None:
            item.БазоваяЕдиницаИзмерения = base_unit
        main_unit = self._first(
            "ВЫБРАТЬ ПЕРВЫЕ 1 Е.Ссылка КАК Ссылка ИЗ Справочник.ЕдиницыИзмерения КАК Е "
            "ГДЕ Е.Наименование = &Н И Е.Владелец = &Т", {"Н": "шт", "Т": part_type})
        if main_unit is not None:
            item.ОсновнаяЕдиницаИзмерения = main_unit
        item.СтавкаНДС = self._default_vat()
        item.ВалютаУчета = self._accounting_currency()
        article = " ".join(article.split()) or "".join(name.split())[:25]
        item.Артикул = article
        item.АртикулДляПоиска = self.normalize_article(article)
        self._write(item, "запчасть")
        return item.Ссылка

    def add_part(self, name: str, article: str = "") -> Dict:
        """Добавляет запчасть в справочник «Номенклатура» (в группу «Запчасти для разнесения»).

        Параметры: name — наименование; article — артикул (пусто — создаётся из названия: название без
        пробелов, до 25 символов). Запчасть считается существующей, если в справочнике уже есть товар с
        таким артикулом (1С не допускает одинаковые артикулы); тогда ничего не создаётся.
        Возвращает {"created": True/False, "name": наименование, "article": артикул, "folder": группа};
        для уже существующей — её наименование и артикул.
        Исключение: OneCError при отказе 1С или ошибке связи.
        """
        self._ensure()
        name = " ".join(name.split())
        article = " ".join(article.split())
        final_article = article or "".join(name.split())[:25]
        found = self.find_parts_by_article(final_article)
        if found:
            return {"created": False, "name": found[0]["name"], "article": found[0]["article"],
                    "folder": self.PARTS_GROUP}
        try:
            self.c.НачатьТранзакцию()
            try:
                self._create_part(name, article)
                self.c.ЗафиксироватьТранзакцию()
            except Exception:
                self.c.ОтменитьТранзакцию()
                raise
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка добавления запчасти: %s", e)
            raise OneCError("Ошибка связи с 1С при добавлении запчасти.")
        return {"created": True, "name": name, "article": final_article, "folder": self.PARTS_GROUP}

    def _work_in_order(self, order_ref, work_ref) -> bool:
        """Проверяет, есть ли работа уже в табличной части «Работы» заказ-наряда.

        1С не допускает одинаковые работы в разных строках одного ЗН, поэтому проверка делается
        заранее, чтобы показать понятную причину. Возвращает True/False.
        """
        q = self.c.NewObject("Запрос")
        q.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 1 КАК Признак ИЗ Документ.ЗаказНаряд.Работы КАК Р "
                   "ГДЕ Р.Ссылка = &Д И Р.Работа = &Р")
        q.УстановитьПараметр("Д", order_ref)
        q.УстановитьПараметр("Р", work_ref)
        return not q.Выполнить().Пустой()

    def _default_vat(self):
        """Возвращает ставку НДС «Без НДС» (или пустую ссылку, если такой нет) для строк работ."""
        sel = self._query("ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.СтавкиНДС КАК С ГДЕ С.Наименование = &Н",
                          {"Н": "Без НДС"})
        return sel.Ссылка if sel.Следующий() else self.c.Справочники.СтавкиНДС.ПустаяСсылка()

    def get_norm_hour(self) -> Dict:
        """Действующий нормочас из справочника «Нормочасы»: {"price": цена нормочаса, "currency": валюта}.

        Берётся первый не помеченный на удаление нормочас (так же, как при добавлении работы в ЗН).
        Исключение: OneCError, если нормочаса нет или нет связи.
        """
        self._ensure()
        try:
            sel = self._query(
                "ВЫБРАТЬ ПЕРВЫЕ 1 Н.Цена КАК Цена, Н.Валюта.Наименование КАК Валюта ИЗ Справочник.Нормочасы КАК Н "
                "ГДЕ НЕ Н.ПометкаУдаления УПОРЯДОЧИТЬ ПО Н.Код")
            if not sel.Следующий():
                raise OneCError("В 1С не найден нормочас.")
            return {"price": float(sel.Цена), "currency": sel.Валюта or ""}
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка чтения нормочаса: %s", e)
            raise OneCError("Ошибка чтения нормочаса из 1С.")

    def add_work_to_order(self, order_id: str, hours: float, work_id: str = "", new_work_name: str = "",
                          assign_executor: bool = False, amount: Optional[float] = None) -> Dict:
        """Добавляет работу в заказ-наряд «В работе» и при необходимости создаёт её в справочнике.

        Параметры:
            order_id: идентификатор ЗН.
            hours: количество нормочасов (> 0).
            work_id: идентификатор существующей работы; либо
            new_work_name: название новой работы (создаётся в группе «Работы для разнесения»).

        Расчёт как в форме ЗН: цена = цена нормочаса из справочника «Нормочасы», сумма = нормочасы × цена,
        НДС берётся из первой строки ЗН (иначе «Без НДС»). Если документ проведён, он перепроводится
        (РежимЗаписиДокумента.Проведение), итоги пересчитывает сама 1С.

        Всё выполняется в одной транзакции: при ошибке не остаётся ни новой работы, ни изменений в ЗН.
        Если задана amount (сумма за работу), количество нормочасов вычисляется как сумма / цена действующего
        нормочаса (округление до 3 знаков, как хранит 1С), а в строку пишутся эти часы и сумма ровно в том
        размере, как её ввели; параметр hours тогда игнорируется.

        Если assign_executor=True, на работу ставится исполнитель по умолчанию (default_executor):
        строка в таблице «Исполнители» ЗН с процентом 100 и цехом сотрудника.

        Возвращает {"created_work": bool, "work": название, "total": новая сумма работ ЗН,
        "line_sum": сумма добавленной строки, "hours": записанные нормочасы, "norm_price": цена нормочаса,
        "executor": ФИО исполнителя или ""}.
        Исключение: OneCError (работа уже в ЗН, ЗН не «В работе», отказ 1С при записи/проведении).
        """
        self._ensure()
        if not work_id and not new_work_name:
            raise OneCError("Не указана работа.")
        try:
            self.c.НачатьТранзакцию()
            try:
                created = not work_id
                if work_id:
                    guid = self.c.NewObject("УникальныйИдентификатор", work_id)
                    work_ref = self.c.Справочники.Автоработы.ПолучитьСсылку(guid)
                else:
                    work_ref = self._create_work(new_work_name)
                norm = self._query(
                    "ВЫБРАТЬ ПЕРВЫЕ 1 Н.Ссылка КАК Ссылка, Н.Цена КАК Цена ИЗ Справочник.Нормочасы КАК Н "
                    "ГДЕ НЕ Н.ПометкаУдаления УПОРЯДОЧИТЬ ПО Н.Код")
                if not norm.Следующий():
                    raise OneCError("В 1С не найден нормочас.")
                order_ref = self._order_ref(order_id)
                if work_id and self._work_in_order(order_ref, work_ref):
                    raise OneCError("Эта работа уже есть в заказ-наряде (1С не допускает дубли строк).")
                doc = order_ref.ПолучитьОбъект()
                if self.c.String(doc.Состояние) != "В работе":
                    raise OneCError("ЗН уже не в состоянии «В работе».")
                vat = doc.Работы.Получить(0).СтавкаНДС if doc.Работы.Количество() else self._default_vat()
                price = float(norm.Цена)
                if amount is not None:
                    if price <= 0:
                        raise OneCError("Цена нормочаса в 1С равна нулю, пересчитать сумму в часы нельзя.")
                    hours = round(amount / price, 3)
                    if hours <= 0:
                        raise OneCError("Сумма слишком мала: меньше одной тысячной нормочаса.")
                else:
                    amount = round(hours * price, 2)
                row = doc.Работы.Добавить()
                row.Работа = work_ref
                work_uid = str(uuid.uuid4())
                row.ИдентификаторРаботы = work_uid
                row.Количество = hours
                row.Нормочас = norm.Ссылка
                row.Коэффициент = 1
                row.Цена = price
                row.Сумма = amount
                row.СтавкаНДС = vat
                row.СуммаНДС = 0
                row.СуммаВсего = amount
                row.ПакетРабот = str(uuid.uuid4())
                row.НомерПакета = 1
                if assign_executor:
                    executor = self._executor(self.default_executor)
                    ex_row = doc.Исполнители.Добавить()
                    ex_row.ИдентификаторРаботы = work_uid
                    ex_row.Исполнитель = executor.Ссылка
                    ex_row.Цех = executor.Цех
                    ex_row.Процент = 100
                try:
                    if doc.Проведен:
                        doc.Записать(self.c.РежимЗаписиДокумента.Проведение)
                    else:
                        doc.Записать()
                except pywintypes.com_error as e:
                    detail = self._messages()
                    logger.error("ЗН не записан: %s | %s", e, detail)
                    raise OneCError(f"1С не приняла изменение ЗН: {detail or 'ошибка записи'}")
                self.c.ЗафиксироватьТранзакцию()
            except Exception:
                self.c.ОтменитьТранзакцию()
                raise
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка добавления работы: %s", e)
            raise OneCError("Ошибка связи с 1С при добавлении работы.")
        return {"created_work": created, "work": self.c.String(work_ref),
                "total": float(doc.СуммаРаботДокумента), "line_sum": amount, "hours": hours, "norm_price": price,
                "executor": self.default_executor if assign_executor else ""}

    def _executor(self, full_name: str):
        """Находит сотрудника-исполнителя по ФИО (справочник «Сотрудники», признак «Исполнитель») и
        возвращает его объект (нужны ссылка и цех).

        Исключение: OneCError, если имя не задано (ONE_C_DEFAULT_EXECUTOR в .env) или сотрудник не найден.
        """
        if not full_name:
            raise OneCError("Не задан исполнитель по умолчанию (параметр ONE_C_DEFAULT_EXECUTOR в .env).")
        ref = self._first(
            "ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.Сотрудники КАК С "
            "ГДЕ С.Наименование = &Н И С.Исполнитель И НЕ С.ПометкаУдаления И НЕ С.ФлагУволен", {"Н": full_name})
        if ref is None:
            raise OneCError(f"Исполнитель «{full_name}» не найден в 1С среди работающих исполнителей "
                            f"(проверьте ONE_C_DEFAULT_EXECUTOR в .env).")
        return ref.ПолучитьОбъект()

    # Реквизиты шапки, которые новый заказ-наряд берёт из последнего существующего ЗН (образца):
    # организация, подразделение, хоз. операция, валюта и курсы, типы цен, вид ремонта, цех, вид оплаты и т.п.
    ORDER_COPY_FIELDS = (
        "Организация", "ПодразделениеКомпании", "ХозОперация", "ВалютаДокумента", "КурсДокумента",
        "КурсВалютыУпр", "ТипЦен", "ТипЦенРабот", "ВидРемонта", "Цех", "ВидОплаты",
        "КурсВалютыВзаиморасчетов", "РегламентированныйУчет", "АвтоЗакрытиеСделок",
        "ЗакрыватьЗаказыТолькоПоДанномуЗаказНаряду", "ИсполнителиДляВсехРабот")

    def _payment_kind(self, template_order):
        """Вид оплаты (перечисление «Виды оплаты») для новых договоров и ЗН: из образца ЗН, а если там пусто —
        «Произвольная оплата»."""
        value = template_order.ВидОплаты
        if not value.Пустая():
            return value
        return self.c.Перечисления.ВидыОплаты.ПроизвольнаяОплата

    def _client_contract(self, client_ref, template_contract, template_order=None):
        """Возвращает договор взаиморасчётов клиента (основной), а если его нет, создаёт копию договора образца.

        1С сама договор при создании клиента через COM не создаёт, а в ЗН он нужен. Копия берёт все
        условия договора образца (вид, валюта, типы цен, вид оплаты…), владелец — клиент, «Основной» = Да.
        Наименование договора — «Договор б-н от ДД.ММ.ГГ» (дата регистрации клиента), номер договора «б-н».
        Если в договоре образца какое-то обязательное поле пусто (бывает в других базах), оно добирается из
        шапки образца ЗН (template_order): вид оплаты, организация, подразделение, тип цен, валюта.
        Исключение: OneCError, если договора нет и образца для копирования тоже нет.
        """
        ref = self._first(
            "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка ИЗ Справочник.ДоговорыВзаиморасчетов КАК Д "
            "ГДЕ Д.Владелец = &К И НЕ Д.ПометкаУдаления УПОРЯДОЧИТЬ ПО Д.Основной УБЫВ", {"К": client_ref})
        if ref is not None:
            return ref
        if template_contract.Пустая():
            raise OneCError("У клиента нет договора взаиморасчётов, а в образце заказ-наряда договора нет.")
        contract = template_contract.ПолучитьОбъект().Скопировать()
        now = datetime.datetime.now()
        contract.Владелец = client_ref
        contract.Основной = True
        contract.ДатаНачала = now
        contract.ДатаСоздания = now
        registered = now
        try:
            if client_ref.ДатаРегистрации.year > 1900:
                registered = client_ref.ДатаРегистрации
        except Exception:
            pass
        contract.Наименование = self._trim("ДоговорыВзаиморасчетов", f"Договор б-н от {registered:%d.%m.%y}")
        contract.НомерДоговора = "б-н"
        if template_order is not None:
            fallbacks = (("ВидОплаты", self._payment_kind(template_order)),
                         ("Организация", template_order.Организация),
                         ("Подразделение", template_order.ПодразделениеКомпании),
                         ("ТипЦенПродажи", template_order.ТипЦен),
                         ("ВалютаВзаиморасчетов", template_order.ВалютаДокумента))
            for field, value in fallbacks:
                if getattr(contract, field).Пустая() and not value.Пустая():
                    setattr(contract, field, value)
        self._write(contract, "договор клиента")
        logger.info("Создан договор взаиморасчётов для клиента %s", client_ref.Наименование)
        return contract.Ссылка

    def create_work_order(self, client_id: str = "", new_client: Optional[Dict] = None,
                          car_id: str = "", new_car: Optional[Dict] = None) -> Dict:
        """Создаёт заказ-наряд в состоянии «В работе»; при необходимости сначала клиента и автомобиль.

        Параметры (клиент: одно из двух, машина: одно из двух):
            client_id: идентификатор существующего клиента; либо
            new_client: {"name": ФИО или наименование организации, "phone": телефон, "legal": True для
                юридического лица} — клиент будет создан.
            car_id: идентификатор существующего автомобиля клиента; либо
            new_car: {"brand", "model", "gos", "vin", "year"} — машина будет создана и привязана к клиенту.

        Всё выполняется в одной транзакции: если что-то не принято 1С, не создаётся ни клиент, ни машина,
        ни ЗН. Шапку ЗН (организация, подразделение, цены, валюта, курсы, вид ремонта, цех, вид оплаты) бот
        берёт из последнего существующего ЗН; договор — основной договор клиента (при отсутствии создаётся
        копия договора образца). Документ только записывается (Записать), а проведением занимается сама 1С:
        в состоянии «В работе» она проводит документ при записи.

        Возвращает {"id", "number", "customer", "car"}.
        Исключение: OneCError (машина с таким госномером уже есть, нет образца ЗН, отказ 1С, нет связи).
        """
        self._ensure()
        try:
            self.c.НачатьТранзакцию()
            try:
                if new_client:
                    client_id = self.add_client(new_client["name"], new_client.get("phone", ""),
                                                legal=new_client.get("legal", False))["id"]
                client_ref = self._ref("Контрагенты", client_id)
                if new_car:
                    created = self.add_car(client_id, new_car["brand"], new_car["model"], new_car["gos"],
                                           new_car.get("vin", ""), new_car.get("year", 0))
                    if not created["created"]:
                        raise OneCError(f"Машина с номером {new_car['gos']} уже есть в 1С ({created['name']}).")
                    car_id = created["id"]
                car_ref = self._ref("Автомобили", car_id)

                template_ref = self._first(
                    "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка ИЗ Документ.ЗаказНаряд КАК Д "
                    "ГДЕ НЕ Д.ПометкаУдаления УПОРЯДОЧИТЬ ПО Д.Дата УБЫВ")
                if template_ref is None:
                    raise OneCError("В 1С нет ни одного заказ-наряда. Создайте один ЗН вручную: бот берёт из "
                                    "последнего ЗН организацию, цены, валюту и другие настройки.")
                template = template_ref.ПолучитьОбъект()
                state = self._first(
                    "ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.ВидыСостоянийЗаказНарядов КАК С "
                    "ГДЕ С.Наименование = &Н", {"Н": "В работе"})
                if state is None:
                    raise OneCError("В 1С не найдено состояние заказ-наряда «В работе».")

                doc = self.c.Документы.ЗаказНаряд.СоздатьДокумент()
                now = datetime.datetime.now()
                doc.Дата = now
                for field in self.ORDER_COPY_FIELDS:
                    setattr(doc, field, getattr(template, field))
                doc.Заказчик = client_ref
                doc.Контрагент = client_ref
                doc.Автомобиль = car_ref
                doc.ДоговорВзаиморасчетов = self._client_contract(client_ref, template.ДоговорВзаиморасчетов, template)
                if doc.ВидОплаты.Пустая():
                    doc.ВидОплаты = self._payment_kind(template)
                doc.Состояние = state
                doc.Автор = template.Автор
                doc.ДатаМашинозаезда = now
                doc.ДатаСоздания = now
                doc.ДатаНачала = now
                try:
                    doc.Записать()
                except pywintypes.com_error as e:
                    detail = self._messages()
                    logger.error("ЗН не создан: %s | %s", e, detail)
                    raise OneCError(f"1С не приняла заказ-наряд: {detail or 'ошибка записи'}")
                self.c.ЗафиксироватьТранзакцию()
            except Exception:
                if self.c is not None:
                    self.c.ОтменитьТранзакцию()
                raise
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка создания заказ-наряда: %s", e)
            raise OneCError("Ошибка связи с 1С при создании заказ-наряда.")
        number = str(doc.Номер).lstrip("0") or "0"
        logger.info("Создан заказ-наряд №%s", number)
        return {"id": self._ref_id(doc.Ссылка), "number": number,
                "customer": client_ref.Наименование, "car": car_ref.Наименование}

    USED_NOTE = "запчасть б/у"

    def add_customer_part_to_order(self, order_id: str, qty: float, part_id: str = "",
                                   new_part_name: str = "", new_part_article: str = "",
                                   used: bool = False) -> Dict:
        """Добавляет запчасть клиента (вкладка «Материалы заказчика») в заказ-наряд «В работе».

        Параметры:
            order_id: идентификатор ЗН. qty: количество (> 0).
            part_id: идентификатор существующей номенклатуры (запчасти); либо
            new_part_name: название новой запчасти (создаётся в «Номенклатуре», группа
                «Запчасти для разнесения», как в add_part) и new_part_article — её артикул (пусто —
                артикул создаётся автоматически из названия).
            used: запчасть б/у: в строке в поле «Примечание номенклатура печать» пишется «запчасть б/у».

        Единица измерения и коэффициент берутся из карточки запчасти. Если такая запчасть с тем же
        признаком (новая / б/у) уже есть в материалах заказчика этого ЗН, количество увеличивается в
        существующей строке. 1С не допускает две строки одной номенклатуры в этой таблице, поэтому если
        та же номенклатура уже есть с другим признаком (новая вместо б/у или наоборот), бросается OneCError
        с советом добавить её отдельной позицией. Проведённый документ перепроводится. Всё выполняется
        в одной транзакции: при ошибке ничего не остаётся.

        Возвращает {"created_part": bool, "part": название, "article": артикул, "used": bool,
        "qty": добавленное количество, "total_qty": количество в строке ЗН после добавления, "unit": единица}.
        Исключение: OneCError (ЗН не «В работе», отказ 1С при записи/проведении, нет связи).
        """
        self._ensure()
        if not part_id and not new_part_name:
            raise OneCError("Не указана запчасть.")
        try:
            self.c.НачатьТранзакцию()
            try:
                created = not part_id
                if part_id:
                    guid = self.c.NewObject("УникальныйИдентификатор", part_id)
                    part_ref = self.c.Справочники.Номенклатура.ПолучитьСсылку(guid)
                else:
                    part_ref = self._create_part(new_part_name, new_part_article)
                doc = self._order_ref(order_id).ПолучитьОбъект()
                if self.c.String(doc.Состояние) != "В работе":
                    raise OneCError("ЗН уже не в состоянии «В работе».")
                part = part_ref.ПолучитьОбъект()
                unit = part.ОсновнаяЕдиницаИзмерения
                note = self.USED_NOTE if used else ""
                row = None
                for i in range(doc.МатериалыЗаказчика.Количество()):
                    candidate = doc.МатериалыЗаказчика.Получить(i)
                    if self.c.XMLString(candidate.Номенклатура) == self.c.XMLString(part_ref):
                        if (candidate.ПримечаниеНоменклатураПечать or "") != note:
                            was = "б/у" if candidate.ПримечаниеНоменклатураПечать else "новая"
                            raise OneCError(
                                f"Эта запчасть уже есть в ЗН как {was}, а 1С не допускает две строки одной "
                                f"номенклатуры. Добавьте её отдельной позицией («Добавить новую») "
                                f"или измените количество в существующей строке.")
                        row = candidate
                        break
                if row is not None:
                    row.Количество = float(row.Количество) + qty
                else:
                    row = doc.МатериалыЗаказчика.Добавить()
                    row.Номенклатура = part_ref
                    row.Количество = qty
                    row.ЕдиницаИзмерения = unit
                    row.Коэффициент = float(unit.Коэффициент) if not unit.Пустая() and float(unit.Коэффициент) else 1
                    if note:
                        row.ПримечаниеНоменклатураПечать = note
                try:
                    if doc.Проведен:
                        doc.Записать(self.c.РежимЗаписиДокумента.Проведение)
                    else:
                        doc.Записать()
                except pywintypes.com_error as e:
                    detail = self._messages()
                    logger.error("ЗН не записан: %s | %s", e, detail)
                    raise OneCError(f"1С не приняла изменение ЗН: {detail or 'ошибка записи'}")
                self.c.ЗафиксироватьТранзакцию()
            except Exception:
                self.c.ОтменитьТранзакцию()
                raise
        except pywintypes.com_error as e:
            self.c = None
            logger.error("Ошибка добавления запчасти клиента: %s", e)
            raise OneCError("Ошибка связи с 1С при добавлении запчасти клиента.")
        return {"created_part": created, "part": part.Наименование, "article": part.Артикул or "",
                "used": used, "qty": qty, "total_qty": float(row.Количество),
                "unit": self.c.String(row.ЕдиницаИзмерения)}

